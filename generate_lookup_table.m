% Generate 8-bit DAC lookup table for the stated lab signal.
% Output files:
%   lookup_codes.csv
%   lookup_table.inc


clear; clc; close all;

N = 2048;
duration = 1;
t = (0:N-1) / N; % N equally spaced samples over [0, 1), no duplicate endpoint

f1 = 1;
f2 = 30;
x = 0.1*sin(2*pi*f1*t) + 0.05*sin(2*pi*f2*t) + 0.1;

% code = ((x + 2)/4)*255. This is preserved from the supplied report.
codes = uint8(round(((x + 2)/4)*255));
codes = min(max(double(codes), 0), 255);
codes = uint8(codes);

figure('Color','w');
plot(t, double(codes), 'LineWidth', 1);
xlabel('Time (s)');
ylabel('8-bit DAC code');
title('DAC Lookup Table');
grid on;

writematrix([t(:), x(:), double(codes(:))], 'lookup_codes.csv');

fid = fopen('lookup_table.inc', 'w');
if fid == -1
    error('Could not open lookup_table.inc for writing.');
end
fprintf(fid, '; Generated by generate_lookup_table.m\n');
fprintf(fid, '; Include this file inside the AVR assembly DATA table.\n');
fprintf(fid, 'DATA:\n    .DB ');
for k = 1:N
    if k > 1
        if mod(k-1, 16) == 0
            fprintf(fid, '\n    .DB ');
        else
            fprintf(fid, ',');
        end
    end
    fprintf(fid, '0x%02X', codes(k));
end
fprintf(fid, '\n');
fclose(fid);

fprintf('Generated lookup_codes.csv and lookup_table.inc in %s\n', pwd);
